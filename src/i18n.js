export function preferredLanguage(storedLanguage, browserLanguage = '') {
  if (LANGUAGES.includes(storedLanguage)) return storedLanguage;
  return String(browserLanguage).toLowerCase().startsWith('pt') ? 'pt-BR' : 'en';
}

export function trackCopy(track, language) {
  if (language !== 'pt-BR') return { name: track.name, intro: track.intro, day: track.day };
  const copy = portugueseTracks[track.id];
  return copy ?? { name: track.name, intro: track.intro, day: track.day };
}

export function practiceCopy(value, language) {
  return language === 'pt-BR' ? portugueseStages[value] ?? value : value;
}

export function translateText(value, language) {
  if (language !== 'pt-BR') return value;
  let translated = value;
  translated = translated.replace(/Pattern recorded (\d+) times/g, 'Padrão registrado $1 vezes');
  translated = translated.replace(/Saved\. This pattern has been recorded (\d+) times\./g, 'Salvo. Este padrão foi registrado $1 vezes.');
  translated = translated.replace(/(\d+) completed sessions/g, '$1 sessões concluídas');
  translated = translated.replace(/(\d+) completed session/g, '$1 sessão concluída');
  translated = translated.replace(/(\d+) prompts/g, '$1 desafios');
  translated = translated.replace(/(\d+) responses/g, '$1 respostas');
  translated = translated.replace(/(\d+) completed/g, '$1 concluídas');
  for (const [english, portuguese] of Object.entries(ptBR).sort(([left], [right]) => right.length - left.length)) {
    translated = translated.replaceAll(english, portuguese);
  }
  translated = translated.replace(/STEP (\d+) OF (\d+)/g, 'ETAPA $1 DE $2');
  translated = translated.replace(/\b(\d+) MINUTES\b/g, '$1 MINUTOS');
  translated = translated.replace(/\bABOUT (\d+) MIN\b/g, 'CERCA DE $1 MIN');
  return translated;
}

export function translateMarkup(markup, language) {
  return translateText(markup, language);
}
